async def get_text(key: str, **kwargs) -> str:
    override = await db.get_text_override(key)
    template = override if override is not None else TEXT_DEFS[key]["default"]
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except Exception:
        # Если в тексте остались посторонние фигурные скобки — не роняем бота
        return template
