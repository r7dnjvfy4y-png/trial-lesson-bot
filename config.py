import os

from dotenv import load_dotenv

load_dotenv()

BOT_TOKEN = os.getenv("BOT_TOKEN", "")
ADMIN_CHAT_ID = int(os.getenv("ADMIN_CHAT_ID", "0") or "0")

TIMEZONE = os.getenv("TIMEZONE", "Europe/Moscow")

# ---------------------------------------------------------------------------
# Уровни и расписание.
#
# DISPLAY_LEVELS — кнопки, которые видит ученик при выборе уровня.
DISPLAY_LEVELS = ["A2", "B1", "B2"]

# LEVEL_TO_GROUP — какое расписание (группу слотов) использовать для
# каждого уровня. Несколько уровней могут делить одно и то же время
# (сейчас A2 и B1 занимаются вместе, у B2 — отдельные слоты).
LEVEL_TO_GROUP = {
    "A2": "А2-Б1",
    "B1": "А2-Б1",
    "B2": "Б2",
}

# Ключ — день недели (0=Пн, 1=Вт, 2=Ср, 3=Чт, 4=Пт, 5=Сб, 6=Вс).
# Значение — список (время, группа). На один день и группу можно указать
# сколько угодно слотов (например, у "Б2" в субботу два времени).
WEEKLY_SCHEDULE = {
    5: [("14:30", "А2-Б1"), ("15:30", "Б2"), ("16:30", "Б2")],  # суббота
    6: [("10:00", "А2-Б1"), ("11:00", "Б2")],  # воскресенье
}

# Все группы расписания — используется в /slots, чтобы показать
# заполненность по каждой из них.
SCHEDULE_GROUPS = sorted({lvl for slots in WEEKLY_SCHEDULE.values() for _, lvl in slots})

# Максимум учеников в одной группе (на один слот даты+времени)
CAPACITY_PER_SLOT = int(os.getenv("CAPACITY_PER_SLOT", "6"))

# На сколько календарных дней вперёд искать подходящие даты. Если на эту
# неделю слот уже заполнен, бот сам предложит тот же день/время на
# следующей неделе — благодаря этому окну поиска.
DAYS_AHEAD = int(os.getenv("DAYS_AHEAD", "28"))

# За сколько часов до слота его ещё можно забронировать
MIN_NOTICE_HOURS = int(os.getenv("MIN_NOTICE_HOURS", "3"))

STALL_TIMEOUT_MINUTES = int(os.getenv("STALL_TIMEOUT_MINUTES", "20"))

# Сколько минут место держится за человеком, пока он записывает голосовое.
# Если голосового так и нет — бронь снимается и место снова доступно другим.
PENDING_HOLD_MINUTES = int(os.getenv("PENDING_HOLD_MINUTES", "120"))

# Необязательно: ссылка на материалы (например, набор Quizlet), которую
# бот присылает кнопкой сразу после подтверждения записи. Пока ссылки нет —
# кнопка просто не показывается.
QUIZLET_LINK = os.getenv("QUIZLET_LINK", "")

DB_PATH = os.getenv("DB_PATH", "bot.db")
